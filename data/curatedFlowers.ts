export function getCuratedFlowers(userQuery?: string): Flower[] {
  const q = (userQuery || "").trim().toLowerCase();

  // 1. 단일 꽃 이름 매칭
  for (const [key, flower] of Object.entries(curatedSpecialFlowers)) {
    if (q.includes(key.toLowerCase())) {
      return [flower];
    }
  }

  // 2. 월별 매핑 (예: "9월", "9", "가을" 등)
  const monthMatch = q.match(/(\d{1,2})월?/);
  let monthNum = monthMatch ? parseInt(monthMatch[1], 10) : new Date().getMonth() + 1;
  if (isNaN(monthNum) || monthNum < 1 || monthNum > 12) {
    monthNum = new Date().getMonth() + 1;
  }

  if (monthNum >= 3 && monthNum <= 5) {
    return curatedSpringFlowers;
  } else if (monthNum >= 6 && monthNum <= 8) {
    return curatedSummerFlowers;
  } else if (monthNum >= 9 && monthNum <= 11) {
    return curatedAutumnFlowers;
  } else {
    return curatedWinterFlowers;
  }
}
